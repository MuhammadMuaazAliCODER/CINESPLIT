import api from './api.js'

export const getFavorites = (params = {}) => api.get('/favorites/', { params })
export const getFavoriteState = (type, id) => api.get(`/favorites/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`)
export const addFavorite = (type, id) => api.post('/favorites/', { content_type: type, content_id: id })
export const removeFavorite = (type, id) => api.delete(`/favorites/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`)
export const getWatchHistory = (params = {}) => api.get('/watch-history/', { params })
export const getWatchProgress = (type, id) => api.get(`/watch-history/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`)
export const saveWatchProgress = (payload) => api.post('/watch-history/', payload)
export const removeWatchHistory = (type, id) => api.delete(`/watch-history/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`)
export const getReviews = (type, id, params = {}) => api.get(`/reviews/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`, { params })
export const createReview = (type, id, payload) => api.post(`/reviews/${encodeURIComponent(type)}/${encodeURIComponent(id)}/`, payload)
export const updateReview = (type, id, reviewId, payload) => api.patch(`/reviews/${encodeURIComponent(type)}/${encodeURIComponent(id)}/${encodeURIComponent(reviewId)}/`, payload)
export const deleteReview = (type, id, reviewId) => api.delete(`/reviews/${encodeURIComponent(type)}/${encodeURIComponent(id)}/${encodeURIComponent(reviewId)}/`)
export const getDashboard = () => api.get('/admin/analytics/')
export const getMediaLibrary = (params = {}) => api.get('/admin/media/', { params })
export const getDiscovery = (params = {}, config = {}) => api.get('/discover/', { ...config, params })
export const getFeaturedContent = () => api.get('/discover/featured/')
export const getLatestContent = () => api.get('/discover/latest/')
